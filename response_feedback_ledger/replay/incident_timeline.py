class IncidentTimeline:
    name = STAGE

    def apply(self, state: RunState) -> None:
        evaluations = [evaluate_policy(policy, state.payload, state) for policy in POLICIES]
        values = self._business_values(state.payload)
        artifact = self._project(values, evaluations, state)
        state.artifacts[STAGE] = artifact
        state.set_metric(STAGE + "_score", artifact["score"])
        state.emit(STAGE, "stage_evaluated", failed=sum(item["failed"] for item in evaluations), focus=FOCUS, score=artifact["score"])
        state.advance(STAGE)

    def _business_values(self, payload: dict[str, Any]) -> list[float]:
        values = []
        for record in sequence(payload.get("records")):
            if isinstance(record, dict):
                values.append(number(record.get("value", record.get("amount", record.get("weight", 0)))))
            else:
                values.append(number(record))
        for item in sequence(payload.get("timeline")):
            if isinstance(item, dict):
                values.append(number(item.get("end", item.get("value", item.get("rain", 0)))))
        if not values:
            values = [number(payload.get("amount")), number(payload.get("count")), number(payload.get("total"))]
        return values

    def _project(self, values: list[float], evaluations: list[dict[str, Any]], state: RunState) -> dict[str, Any]:
        failed = sum(1 for item in evaluations if item["failed"])
        total = sum(values)
        peak = max(values, default=0.0)
        floor = min(values, default=0.0)
        median = percentile(values, 0.5)
        upper = percentile(values, 0.9)
        weighted = sum((index + 1) * value for index, value in enumerate(values))
        risk = number(get_path(state.payload, "attributes.risk_score"))
        confidence = number(get_path(state.payload, "metrics.confidence"), 0.5)
        coverage = number(get_path(state.payload, "metrics.coverage"), 0.0)
        score = max(0.0, 100.0 - failed * 3.0 + confidence * 8.0 + coverage * 0.1 - risk * 0.05 + (6 + 1) * 0.2)
        bands = {"low": sum(value < median for value in values), "middle": sum(median <= value <= upper for value in values), "high": sum(value > upper for value in values)}
        return {
            "stage": STAGE, "focus": FOCUS, "score": round(score, 6), "failed_rules": failed,
            "sample_count": len(values), "total": round(total, 6), "peak": round(peak, 6), "floor": round(floor, 6),
            "median": round(median, 6), "upper_quantile": round(upper, 6), "weighted_signal": round(weighted, 6),
            "bands": bands, "signature": stable_json({"stage": STAGE, "values": values, "failed": failed}),
        }
